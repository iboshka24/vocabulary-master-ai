/* Real-browser regression: npm run test:browser (npx playwright install chromium). */
const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const http = require('node:http');
const fs = require('node:fs');
const path = require('node:path');
const os = require('node:os');
const root = path.resolve(__dirname, '..');
const output = process.env.VM_SCREENSHOTS || path.join(os.tmpdir(), 'opencode', 'vocabulary-master-screenshots');
fs.mkdirSync(output, { recursive: true });
const mime = {'.html':'text/html; charset=utf-8','.js':'text/javascript; charset=utf-8','.css':'text/css; charset=utf-8','.mp4':'video/mp4'};
const server = http.createServer((req,res) => {
  if (req.url === '/api/ai') { res.setHeader('Content-Type','application/json'); res.end('{"status":"ok","serverKeyConfigured":false}'); return; }
  const file = path.resolve(root, '.' + decodeURIComponent(req.url === '/' ? '/index.html' : req.url.split('?')[0]));
  if (!file.startsWith(root + path.sep)) { res.writeHead(403); res.end(); return; }
  fs.readFile(file, (err,data) => { if(err){res.writeHead(404);res.end();return;}res.setHeader('Content-Type',mime[path.extname(file)] || 'application/octet-stream');res.end(data); });
});
let browser;
(async () => {
  await new Promise(r => server.listen(0,'127.0.0.1',r));
  browser = await chromium.launch({headless:true});
  const page = await browser.newPage({viewport:{width:1440,height:1100},reducedMotion:'reduce'});
  const errors = []; page.on('pageerror',e=>errors.push(e.message));
  await page.goto('http://127.0.0.1:' + server.address().port);
  await page.locator('#sourceLang option').first().waitFor({state:'attached'});
  assert.equal(await page.title(),'Vocabulary Master AI — слова становятся знаниями');
  assert.equal(await page.locator('.bg').evaluate(el=>getComputedStyle(el).display),'none');
  await page.screenshot({path:path.join(output,'01-desktop.png'),fullPage:true});
  await page.click('#btnDemo');
  await page.locator('#screen-train.active').waitFor();
  await page.click('#btnReveal');
  assert(await page.locator('#card').evaluate(el=>el.classList.contains('flipped')));
  await page.click('#btnKnew2');
  await page.waitForTimeout(300);
  assert.equal(await page.locator('#stKnown').innerText(),'1');
  await page.click('#navLibrary');
  await page.locator('.deck-item').waitFor();
  assert.match(await page.locator('#streakCount').innerText(),/^1 /);
  await page.screenshot({path:path.join(output,'02-library.png'),fullPage:true});
  const downloadPromise = page.waitForEvent('download');
  await page.click('#btnExportLibrary');
  const download = await downloadPromise;
  const backup = JSON.parse(fs.readFileSync(await download.path(),'utf8'));
  assert.equal(backup.version,2);
  assert(!JSON.stringify(backup).includes('apiKey'));
  page.once('dialog',d=>d.accept());
  await page.locator('#importLibrary').setInputFiles({name:'backup.json',mimeType:'application/json',buffer:Buffer.from(JSON.stringify(backup))});
  await page.waitForFunction(()=>document.querySelector('#toast').textContent.includes('Библиотека восстановлена'));
  assert.equal(await page.locator('.deck-item').count(),1);
  await page.click('#navStudy');
  await page.click('#modeSeg [data-mode="typing"]');
  await page.click('#dirSeg [data-dir="fwd"]');
  await page.click('#navLibrary');
  await page.click('[data-act="practice"]');
  await page.locator('#typedAnswer').waitFor({state:'visible'});
  await page.fill('#typedAnswer','точно неправильный ответ');
  await page.click('#typingForm button');
  await page.locator('#answerFeedback').waitFor({state:'visible'});
  assert.match(await page.locator('#answerFeedbackText').innerText(),/Правильный ответ/);
  await page.click('#btnNextAnswer');
  await page.waitForTimeout(300);
  assert.equal(await page.locator('#stForgot').innerText(),'1');
  const expected = await page.locator('#cardTrans').innerText();
  await page.fill('#typedAnswer',expected);
  await page.click('#typingForm button');
  assert.match(await page.locator('#answerFeedbackText').innerText(),/^Верно/);
  await page.click('#btnNextAnswer');
  await page.waitForTimeout(300);
  assert.equal(await page.locator('#stKnown').innerText(),'1');
  await page.click('#navTest');
  await page.click('#btnQuizStart');
  for(let i=0;i<5;i++) {
    await page.locator('.quiz-option').first().click();
    assert.equal(await page.locator('.quiz-option.correct').count(),1);
    await page.click('#btnQuizNext');
  }
  assert.equal(await page.locator('#quizProgress').innerText(),'ТЕСТ ЗАВЕРШЁН');
  await page.reload();
  await page.click('#navLibrary');
  assert.equal(await page.locator('.deck-item').count(),1);
  assert.match(await page.locator('#streakCount').innerText(),/^1 /);
  await page.click('#btnTheme');
  assert.equal(await page.locator('html').getAttribute('data-theme'),'dark');
  await page.screenshot({path:path.join(output,'03-dark.png'),fullPage:true});
  await page.click('#btnTheme');
  await page.setViewportSize({width:390,height:844});
  await page.click('#navStudy');
  assert(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth), 'mobile horizontal overflow');
  await page.screenshot({path:path.join(output,'04-mobile.png'),fullPage:true});
  assert.deepEqual(errors,[],'uncaught browser errors');
  console.log('✓ Browser: demo, flashcard, typing, library, lexical test, streak, persistence, themes, mobile');
  console.log('Screenshots: ' + output);
})().catch(err=>{console.error(err);process.exitCode=1;}).finally(async()=>{if(browser)await browser.close();server.close();});
