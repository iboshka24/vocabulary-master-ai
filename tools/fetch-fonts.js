/* Downloads the app's Google Fonts once and serves them from vendor/fonts/ instead of a CDN:
   no third-party requests (privacy, offline, strict CSP font-src 'self').
   Run: node tools/fetch-fonts.js   — rewrites vendor/fonts/fonts.css and the .woff2 files. */
const fs = require('node:fs');
const path = require('node:path');

const CSS_URL = 'https://fonts.googleapis.com/css2?family=Fraunces:ital,opsz,wght@0,9..144,500..900;1,9..144,500..900' +
  '&family=Inter:wght@400;500;600;700&family=JetBrains+Mono:wght@500;700&display=swap';
const SUBSETS = ['latin', 'latin-ext', 'cyrillic', 'cyrillic-ext']; // RU, UZ (Latin) and EN interface text
const LICENSES = { Fraunces: 'fraunces', Inter: 'inter', 'JetBrains Mono': 'jetbrainsmono' };
const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/130.0.0.0 Safari/537.36';
const out = path.join(__dirname, '..', 'vendor', 'fonts');

async function get(url, binary) {
  const res = await fetch(url, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(url + ' → HTTP ' + res.status);
  return binary ? Buffer.from(await res.arrayBuffer()) : res.text();
}

(async () => {
  fs.mkdirSync(out, { recursive: true });
  const css = await get(CSS_URL);
  const blocks = css.split(/(?=\/\* [a-z-]+ \*\/)/).filter(b => b.includes('@font-face'));
  const files = new Map();
  const kept = blocks.filter(b => SUBSETS.includes(b.match(/\/\* ([a-z-]+) \*\//)[1])).map(b => {
    const subset = b.match(/\/\* ([a-z-]+) \*\//)[1];
    const family = b.match(/font-family: '([^']+)'/)[1];
    const style = b.match(/font-style: (\w+)/)[1];
    const url = b.match(/url\((https:[^)]+)\)/)[1];
    const name = `${family.toLowerCase().replace(/\s+/g, '-')}-${style}-${subset}.woff2`;
    files.set(url, name);
    return b.replace(url, name);
  });
  for (const [url, name] of files) fs.writeFileSync(path.join(out, name), await get(url, true));
  fs.writeFileSync(path.join(out, 'fonts.css'), '/* Generated by tools/fetch-fonts.js from Google Fonts (SIL Open Font License 1.1, see OFL-*.txt). */\n' + kept.join(''));
  for (const [family, dir] of Object.entries(LICENSES)) {
    const text = await get(`https://raw.githubusercontent.com/google/fonts/main/ofl/${dir}/OFL.txt`);
    fs.writeFileSync(path.join(out, `OFL-${dir}.txt`), text);
  }
  console.log(`vendor/fonts: ${kept.length} faces, ${files.size} files, licenses for ${Object.keys(LICENSES).join(', ')}`);
})().catch(e => { console.error(e.message); process.exitCode = 1; });
