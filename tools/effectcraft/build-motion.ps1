# ============================================================================
#  build-motion.ps1 — builds the EffectCraft "Streak Celebration" motion piece
#  and exports every artifact the web app's Motion Lab can compare against.
#
#  Usage:
#    powershell -ExecutionPolicy Bypass -File build-motion.ps1 [-CliPath <path>]
#
#  CLI discovery order: -CliPath param  ->  $env:EFFECTCRAFT_CLI  ->  portable
#  build in %TEMP%\opencode\effectcraft  ->  "C:\Program Files\EffectCraft".
# ============================================================================
param(
  [string]$CliPath = ""
)

$ErrorActionPreference = "Continue"
$root     = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)   # vocabulary-master-ai\
$here     = $PSScriptRoot
$buildDir = Join-Path $here "build"
$motionDir = Join-Path $root "motion"
New-Item -ItemType Directory -Force -Path $buildDir, $motionDir | Out-Null

# ── find effectcraft-cli ─────────────────────────────────────────────────────
$candidates = @()
if ($CliPath) { $candidates += $CliPath }
if ($env:EFFECTCRAFT_CLI) { $candidates += $env:EFFECTCRAFT_CLI }
$candidates += (Join-Path $env:TEMP "opencode\effectcraft\x64\effectcraft-0.10.0-windows-x64-portable\effectcraft-cli.exe")
$candidates += "C:\Program Files\EffectCraft\effectcraft-cli.exe"

$cli = $candidates | Where-Object { $_ -and (Test-Path $_) } | Select-Object -First 1
if (-not $cli) {
  Write-Error "effectcraft-cli.exe not found. Pass -CliPath, or set `$env:EFFECTCRAFT_CLI, or install EffectCraft. See https://getartcraft.com/apps/effectcraft"
  exit 1
}
Write-Host "Using CLI: $cli"

$ecproj   = Join-Path $buildDir "streak-celebration.ecproj"
$lottie   = Join-Path $motionDir "streak-celebration.json"
$mp4      = Join-Path $motionDir "streak-celebration.mp4"
$gif      = Join-Path $motionDir "streak-celebration.gif"

# ── 1. build the composition ─────────────────────────────────────────────────
Write-Host "`n[1/5] Building composition (streak-celebration.jsx)…"
& $cli script (Join-Path $here "streak-celebration.jsx") --empty --save-as $ecproj --json
if ($LASTEXITCODE -ne 0) { Write-Error "build script failed"; exit 1 }

# ── 2. export Lottie JSON ────────────────────────────────────────────────────
# (done from a generated JSX wrapper: PowerShell 5.1 mangles embedded quotes
#  when passing JSON as a CLI argument to a native executable)
Write-Host "`n[2/5] Exporting Lottie…"
$lottiePosix = $lottie -replace '\\', '/'
$exportJsx = Join-Path $buildDir "_export-lottie.jsx"
@"
var res = app.run('file.exportLottie', {comp: 'StreakCelebration', path: '$lottiePosix', textAsShapes: true});
writeLn('exported: ' + JSON.stringify(res));
"@ | Set-Content -Path $exportJsx -Encoding UTF8
& $cli script $exportJsx $ecproj --json
if ($LASTEXITCODE -ne 0) { Write-Error "Lottie export failed"; exit 1 }

# wrap the JSON into a plain <script> file so the web app can load it from
# file:// without fetch() CORS restrictions
Write-Host "       wrapping into motion/effectcraft-motion.js"
$json = Get-Content -Raw $lottie
Set-Content -Path (Join-Path $motionDir "effectcraft-motion.js") -Value ("// EffectCraft Lottie export - generated by tools/effectcraft/build-motion.ps1`nwindow.VM_EC_LOTTIE = " + $json + ";`n") -Encoding UTF8

# ── 3. render MP4 (h264) ─────────────────────────────────────────────────────
Write-Host "`n[3/5] Rendering MP4…"
& $cli render --comp StreakCelebration --out $mp4 --format h264 --project $ecproj --json 2>$null | Out-Host
if ($LASTEXITCODE -ne 0) { Write-Error "MP4 render failed"; exit 1 }

# ── 4. render GIF ────────────────────────────────────────────────────────────
Write-Host "`n[4/5] Rendering GIF…"
& $cli render --comp StreakCelebration --out $gif --format gif --quality draft --project $ecproj --json 2>$null | Out-Host
if ($LASTEXITCODE -ne 0) { Write-Error "GIF render failed"; exit 1 }

# ── 5. render stills (poster frames) ─────────────────────────────────────────
Write-Host "`n[5/5] Rendering still frames…"
foreach ($t in @(0.6, 1.4, 2.2, 3.2)) {
  $png = Join-Path $motionDir ("streak-frame-{0}.png" -f ($t * 10))
  & $cli render-frame --comp StreakCelebration --time $t --max-side 640 --out $png --project $ecproj --json 2>$null | Out-Null
  if ($LASTEXITCODE -ne 0) { Write-Error "still frame render failed at t=$t"; exit 1 }
}

Write-Host "`nArtifacts:"
Get-ChildItem $motionDir | ForEach-Object { "  {0,-40} {1,10:N0} bytes" -f $_.Name, $_.Length }
Get-ChildItem $buildDir | ForEach-Object { "  {0,-40} {1,10:N0} bytes" -f $_.Name, $_.Length }
Write-Host "`nDone."
