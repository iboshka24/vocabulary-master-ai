param([string]$CliPath = $env:EFFECTCRAFT_CLI)
$ErrorActionPreference = 'Stop'
if (-not $CliPath) { $CliPath = Join-Path $env:TEMP 'opencode\effectcraft\x64\effectcraft-0.10.0-windows-x64-portable\effectcraft-cli.exe' }
if (-not (Test-Path $CliPath)) { throw 'Pass -CliPath pointing to EffectCraft CLI v0.10.0.' }
$root = Split-Path -Parent (Split-Path -Parent $PSScriptRoot)
$project = Join-Path $PSScriptRoot 'build\editorial-achievement.ecproj'
$json = Join-Path $root 'motion\editorial-achievement.json'
$export = Join-Path $PSScriptRoot 'build\_export-editorial.jsx'
New-Item -ItemType Directory -Force (Split-Path $project) | Out-Null
& $CliPath script (Join-Path $PSScriptRoot 'editorial-achievement.jsx') --empty --save-as $project --json
if ($LASTEXITCODE -ne 0) { throw 'EffectCraft composition failed.' }
$target = $json.Replace('\','/')
"var result = app.run('file.exportLottie', {comp:'EditorialAchievement', path:'$target', textAsShapes:true}); writeLn(JSON.stringify(result));" | Set-Content $export -Encoding UTF8
& $CliPath script $export $project --json
if ($LASTEXITCODE -ne 0) { throw 'EffectCraft Lottie export failed.' }
$data = Get-Content $json -Raw
"// Generated by EffectCraft CLI. Source: tools/effectcraft/editorial-achievement.jsx`nwindow.VM_EDITORIAL_MOTION = $data;" | Set-Content (Join-Path $root 'motion\editorial-achievement.js') -Encoding UTF8
Write-Host 'Built motion/editorial-achievement.json and .js from EffectCraft.'
